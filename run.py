"""Run every SQL file in order against data/minigrid.duckdb and export the analysis results.

    python run.py

1. sql/00-10: load the raw CSVs and build the cleaning views (all cleaning is in SQL).
2. sql/20_analysis/a1-a6: run each question and save it to results/<name>.csv.
3. Write results/RESULTS.md with the first rows of every answer.
"""

import logging
import re
import sys
from pathlib import Path

import duckdb
import pandas as pd

ROOT = Path(__file__).resolve().parent
SQL_DIR = ROOT / "sql"
ANALYSIS_DIR = SQL_DIR / "20_analysis"
RAW_DIR = ROOT / "data" / "raw"
DB_PATH = ROOT / "data" / "minigrid.duckdb"
RESULTS_DIR = ROOT / "results"
PREVIEW_ROWS = 10

# Finds the name of every table or view a SQL file creates, e.g. "clean_customers".
CREATED_OBJECT = re.compile(r"CREATE OR REPLACE (?:TABLE|VIEW) (\w+)", re.IGNORECASE)

logger = logging.getLogger("run")

QUESTIONS = {
    "a1_monthly_energy_by_community": "Monthly energy use per community",
    "a2_revenue_vs_consumption": "Revenue collected vs cost of energy consumed, per plan, per month",
    "a3_top_customers_rank": "Top 10 customers by consumption (RANK)",
    "a4_rolling_7day_usage": "Rolling 7-day average usage per customer (window frame)",
    "a5_customers_at_risk": "Customers who used energy but paid nothing in the last 14 days",
    "a6_users_per_plan": "Distinct customers per plan",
}


def build_views(connection: duckdb.DuckDBPyConnection, raw_dir: Path) -> None:
    """Run sql/00_*.sql to sql/10_*.sql in name order and log each object's row count."""
    for sql_file in sorted(SQL_DIR.glob("*.sql")):
        sql = sql_file.read_text(encoding="utf-8").replace("{raw_dir}", raw_dir.as_posix())
        connection.execute(sql)
        for name in CREATED_OBJECT.findall(sql):
            rows = connection.execute(f"SELECT COUNT(*) FROM {name}").fetchone()[0]
            logger.info("%-28s -> %-22s %7d rows", sql_file.name, name, rows)


def run_analysis(connection: duckdb.DuckDBPyConnection) -> dict[str, pd.DataFrame]:
    results = {}
    for sql_file in sorted(ANALYSIS_DIR.glob("*.sql")):
        results[sql_file.stem] = connection.execute(sql_file.read_text(encoding="utf-8")).df()
        logger.info("%-36s %7d rows", sql_file.name, len(results[sql_file.stem]))
    return results


def to_markdown_table(table: pd.DataFrame) -> str:
    """A plain Markdown table, so GitHub shows the results without running anything."""
    cells = table.astype(object).where(table.notna(), "")
    header = "| " + " | ".join(table.columns) + " |"
    divider = "|" + "|".join("---" for _ in table.columns) + "|"
    rows = ["| " + " | ".join(str(value) for value in row) + " |" for row in cells.to_numpy()]
    return "\n".join([header, divider, *rows])


def write_results(results: dict[str, pd.DataFrame], results_dir: Path) -> None:
    results_dir.mkdir(parents=True, exist_ok=True)
    sections = [
        "# Results",
        "",
        "Generated by `python run.py`. Each section shows the first "
        f"{PREVIEW_ROWS} rows; the full answers are in the CSV files next to this one.",
    ]
    for name, table in results.items():
        # DuckDB DATE columns arrive as date-times; show them as plain dates.
        for column in table.select_dtypes(include="datetime").columns:
            table[column] = table[column].dt.date
        table.to_csv(results_dir / f"{name}.csv", index=False)
        sections += [
            "",
            f"## {name}: {QUESTIONS.get(name, '')}",
            "",
            f"Query: [`sql/20_analysis/{name}.sql`](../sql/20_analysis/{name}.sql) · "
            f"{len(table):,} rows · [full CSV]({name}.csv)",
            "",
            to_markdown_table(table.head(PREVIEW_ROWS)),
        ]
    (results_dir / "RESULTS.md").write_text("\n".join(sections) + "\n", encoding="utf-8")
    logger.info("Wrote %d CSV files and RESULTS.md to %s", len(results), results_dir)


def run(
    raw_dir: Path = RAW_DIR, db_path: Path = DB_PATH, results_dir: Path = RESULTS_DIR
) -> dict[str, pd.DataFrame]:
    if not (raw_dir / "customers.csv").exists():
        raise FileNotFoundError(f"No data in {raw_dir}. Run 'python scripts/generate_data.py'.")
    db_path.parent.mkdir(parents=True, exist_ok=True)
    with duckdb.connect(str(db_path)) as connection:
        build_views(connection, raw_dir)
        results = run_analysis(connection)
    write_results(results, results_dir)
    return results


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(message)s", datefmt="%H:%M:%S")
    run()
    sys.exit(0)
